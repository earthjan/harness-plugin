#!/usr/bin/env node
/**
 * Maintains the tickets registry at docs/tickets/INDEX.md.
 *
 * Conventions:
 * - Every ticket directory (docs/tickets/<id>/) has a CONTEXT.md with frontmatter.
 * - Required frontmatter: title, description.
 * - Optional frontmatter: id, state, labels (list), repo, updated (ISO date).
 *
 * Usage:
 *   node docs/tickets/update-tickets-index.mjs           # regenerate INDEX.md
 *   node docs/tickets/update-tickets-index.mjs --check   # report only, exit 1 on problems
 *   node docs/tickets/update-tickets-index.mjs --init    # scaffold CONTEXT.md for dirs that lack it
 */
import {
    readFileSync,
    readdirSync,
    statSync,
    writeFileSync
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ticketsDir = dirname(fileURLToPath(import.meta.url));
const indexFile = join(ticketsDir, "INDEX.md");
const stubTemplate = `---
title: TBD
description: TBD
state: open
labels: []
updated: ${new Date().toISOString().slice(0, 10)}
---

# Ticket <id> — Context

<Fill in the ticket context here.>
`;

function cleanValue(value) {
  const trimmed = value.trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function parseFrontmatter(raw) {
  if (!raw.startsWith("---")) return null;
  const end = raw.indexOf("\n---", 3);
  if (end === -1) return null;
  const fm = {};
  let currentKey = null;
  for (const line of raw.slice(3, end).split("\n")) {
    const trimmed = line.trim();
    if (trimmed === "") continue;
    if (currentKey && /^\s+-\s+/.test(line)) {
      fm[currentKey].push(cleanValue(trimmed.replace(/^-\s+/, "")));
      continue;
    }
    const match = trimmed.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!match) continue;
    const [, key, rest] = match;
    const value = rest.trim();
    if (value === "") {
      fm[key] = [];
      currentKey = key;
    } else if (value.startsWith("[") && value.endsWith("]")) {
      fm[key] = value
        .slice(1, -1)
        .split(",")
        .map((item) => cleanValue(item))
        .filter(Boolean);
      currentKey = null;
    } else {
      fm[key] = cleanValue(value);
      currentKey = null;
    }
  }
  return fm;
}

const REQUIRED_FIELDS = ["title", "description"];
const OPTIONAL_FIELDS = ["id", "state", "labels", "repo", "updated"];
const FIELDS = [...REQUIRED_FIELDS, ...OPTIONAL_FIELDS];

function scan() {
  const entries = readdirSync(ticketsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name, undefined, { numeric: true }));
  const warnings = [];
  const tickets = [];
  for (const entry of entries) {
    const ticketDir = join(ticketsDir, entry.name);
    const contextFile = join(ticketDir, "CONTEXT.md");
    let fm = {};
    let hasContext = false;
    try {
      if (statSync(contextFile).isFile()) {
        hasContext = true;
        fm = parseFrontmatter(readFileSync(contextFile, "utf8")) ?? {};
        if (!Object.keys(fm).length) {
          warnings.push(
            `${entry.name}/CONTEXT.md — present but has no valid frontmatter`,
          );
        }
      }
    } catch {
      hasContext = false;
    }
    if (!hasContext) {
      warnings.push(`${entry.name}/ — no CONTEXT.md`);
    }
    for (const field of REQUIRED_FIELDS) {
      const value = fm[field];
      if (!value || value === "TBD" || value === "tbd") {
        warnings.push(
          `${entry.name}/CONTEXT.md — missing required frontmatter field: ${field}`,
        );
      }
    }
    tickets.push({ id: entry.name, hasContext, fm });
  }
  return { tickets, warnings };
}

function renderIndex({ tickets, warnings }) {
  const lines = [];
  lines.push("# Tickets Index");
  lines.push("");
  lines.push(
    "> Auto-generated by `update-tickets-index.mjs`. Do not edit by hand.",
  );
  lines.push("> Regenerate with: `node docs/tickets/update-tickets-index.mjs`");
  lines.push(
    "> Convention: each `docs/tickets/<id>/` has a `CONTEXT.md` whose frontmatter carries at least `title` and `description`. This index is the registry of those frontmatters.",
  );
  lines.push("");
  lines.push("## Registry");
  lines.push("");
  const header = [
    "Ticket",
    "Title",
    "State",
    "Labels",
    "Repo",
    "Updated",
    "Description",
  ];
  lines.push(`| ${header.join(" | ")} |`);
  lines.push(`| ${header.map(() => "---").join(" | ")} |`);
  const visible = tickets.filter((ticket) => ticket.hasContext);
  for (const ticket of visible) {
    const fm = ticket.fm;
    const value = (field) => {
      if (field === "labels") {
        const labels = fm.labels;
        return Array.isArray(labels) && labels.length ? labels.join(", ") : "—";
      }
      const v = fm[field];
      if (v === undefined || v === null || v === "" || v === "TBD") return "—";
      return String(v);
    };
    const cells = [
      `[${ticket.id}](/${ticket.id}/CONTEXT.md)`,
      value("title"),
      value("state"),
      value("labels"),
      value("repo"),
      value("updated"),
      value("description"),
    ];
    lines.push(`| ${cells.map((c) => c.replace(/\|/g, "\\|")).join(" | ")} |`);
  }
  if (!visible.length) lines.push("| _No tickets with CONTEXT.md yet._ |");
  lines.push("");
  lines.push("## Needs attention");
  lines.push("");
  if (warnings.length) {
    for (const warning of warnings) lines.push(`- ${warning}`);
  } else {
    lines.push(
      "- None — every ticket directory has a CONTEXT.md with `title` and `description`.",
    );
  }
  lines.push("");
  lines.push("## Usage");
  lines.push("");
  lines.push(
    "- **Agents:** read this file first to locate a ticket, then read only that directory's `CONTEXT.md` frontmatter before opening any other file inside it. Do not read every file in a ticket directory.",
  );
  lines.push(
    "- **Maintenance:** `--check` verifies every ticket has valid frontmatter (exit 1 on problems); `--init` scaffolds `CONTEXT.md` for directories that lack it.",
  );
  lines.push("");
  return lines.join("\n");
}

function report({ tickets, warnings }) {
  console.log(`${tickets.length} ticket directories scanned`);
  console.log(
    `${tickets.filter((t) => t.hasContext).length} with CONTEXT.md, ${tickets.filter((t) => !t.hasContext).length} without`,
  );
  if (warnings.length) {
    console.log("Warnings:");
    for (const warning of warnings) console.log(`  - ${warning}`);
  } else {
    console.log("Warnings: none");
  }
}

const args = process.argv.slice(2);
const modeCheck = args.includes("--check");
const modeInit = args.includes("--init");

const { tickets, warnings } = scan();

if (modeInit) {
  let created = 0;
  for (const ticket of tickets) {
    if (!ticket.hasContext) {
      const contextFile = join(ticketsDir, ticket.id, "CONTEXT.md");
      writeFileSync(contextFile, stubTemplate.replace("<id>", ticket.id));
      created += 1;
      console.log(
        `Created ${ticket.id}/CONTEXT.md (stub — fill in title and description)`,
      );
    }
  }
  if (!created) console.log("No missing CONTEXT.md files to create.");
}

if (modeCheck) {
  report({ tickets, warnings });
  const hasProblems = warnings.length > 0;
  console.log(hasProblems ? "CHECK FAILED" : "CHECK PASSED");
  process.exit(hasProblems ? 1 : 0);
}

writeFileSync(indexFile, renderIndex({ tickets, warnings }));
report({ tickets, warnings });
console.log(`Wrote ${indexFile}`);
